classdef TimeFeatures < FeatureGroup
    % 22 time-domain features (on |x|). New feature = new row in registry().
    methods
        function r = registry(~)
            r = { ...
                'Peak',               @TimeFeatures.peak; ...
                'RMS',                @TimeFeatures.rootMeanSquare; ...
                'Kurtosis',           @(x) TimeFeatures.normMoment(x, 4); ...
                'Crest_Factor',       @TimeFeatures.crest; ...
                'Clearance_Factor',   @TimeFeatures.clearance; ...
                'Impulse_Factor',     @TimeFeatures.impulse; ...
                'Shape_Factor',       @TimeFeatures.shape; ...
                'Skewness',           @(x) TimeFeatures.normMoment(x, 3); ...
                'SMR',                @TimeFeatures.squareMeanRoot; ...
                'M5_Norm',            @(x) TimeFeatures.normMoment(x, 5); ...
                'M6_Norm',            @(x) TimeFeatures.normMoment(x, 6); ...
                'Mean',               @TimeFeatures.meanAbs; ...
                'Shape_Factor_2',     @TimeFeatures.shape2; ...
                'Peak_to_Peak',       @TimeFeatures.peakToPeak; ...
                'Kurtosis_Factor',    @TimeFeatures.kurtosisFactor; ...
                'Std',                @TimeFeatures.stdAbs; ...
                'Smoothness',         @TimeFeatures.smoothness; ...
                'Uniformity',         @TimeFeatures.uniformity; ...
                'Neg_Log_Likelihood', @TimeFeatures.negLogLikelihood; ...
                'AC_DC_Ratio',        @TimeFeatures.acDcRatio; ...
                'TKEO_Mean',          @TimeFeatures.tkeoMean; ...
                'TKEO_Kurtosis',      @TimeFeatures.tkeoKurtosis};
        end
    end
    methods (Static)
        function v = peak(x), v = max(abs(x)); end
        function v = rootMeanSquare(x), v = sqrt(mean(abs(x).^2)); end
        function v = normMoment(x, n), e = abs(x(:)); v = mean(((e - mean(e)) / (std(e, 1) + eps)).^n); end
        function v = crest(x), v = TimeFeatures.peak(x) / (TimeFeatures.rootMeanSquare(x) + eps); end
        function v = clearance(x), e = abs(x(:)); v = max(e) / (mean(sqrt(e))^2 + eps); end
        function v = impulse(x), e = abs(x(:)); v = max(e) / (mean(e) + eps); end
        function v = shape(x), e = abs(x(:)); v = TimeFeatures.rootMeanSquare(x) / (mean(e) + eps); end
        function v = squareMeanRoot(x), e = abs(x(:)); v = (mean(sqrt(e)))^2; end
        function v = meanAbs(x), v = mean(abs(x)); end
        function v = shape2(x), v = TimeFeatures.squareMeanRoot(x) / (TimeFeatures.meanAbs(x) + eps); end
        function v = peakToPeak(x), e = abs(x(:)); v = max(e) - min(e); end
        function v = kurtosisFactor(x), v = TimeFeatures.normMoment(x, 4) / (TimeFeatures.rootMeanSquare(x)^4 + eps); end
        function v = stdAbs(x), v = std(abs(x(:)), 1); end
        function v = smoothness(x), v = 1 - (1 / (1 + var(abs(x(:)), 1))); end
        function v = uniformity(x), v = 1 - (TimeFeatures.stdAbs(x) / (TimeFeatures.meanAbs(x) + eps)); end
        function v = negLogLikelihood(x)
            e = abs(x(:)); mu = mean(e); sigma = std(e, 1);
            v = mean((1 / (sigma * sqrt(2*pi) + eps)) * exp(-((e - mu).^2) / (2 * sigma^2 + eps)));
        end
        function v = acDcRatio(x), e = abs(x(:)); v = std(e, 1) / (abs(mean(e)) + eps); end
        function psi = tkeo(x), x = x(:); psi = abs(x(2:end-1)).^2 - real(x(1:end-2) .* conj(x(3:end))); end
        function v = tkeoMean(x), v = mean(TimeFeatures.tkeo(x)); end
        function v = tkeoKurtosis(x)
            psi = TimeFeatures.tkeo(x);
            v = mean(((psi - mean(psi)) / (std(psi, 1) + eps)).^4);
        end
    end
end
