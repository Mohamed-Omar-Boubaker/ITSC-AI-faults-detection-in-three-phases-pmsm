classdef ModelBundleWriter
    % Saves everything the inference script needs to reproduce the training pipeline
    methods (Static)
        function write(path, b)
            bundle = struct( ...
                'model',             compact(b.model), ...    % compact model: no training data
                'collapser',         b.collapser, ...         % family collapse (fitted on train)
                'variance_filter',   b.varianceFilter, ...
                'scaler',            b.scaler, ...
                'raw_feature_names', {b.rawFeatureNames}, ... % features present in the training DB
                'feature_names',     {b.featureNames}, ...    % final (collapsed) feature names
                'mu',                b.scaler.Mu, ...
                'sigma',             b.scaler.Sigma, ...
                'valid_cols',        b.varianceFilter.Valid, ...
                'best_params',       b.bestParams, ...
                'CFG',               b.cfg, ...
                'edges_final',       b.edges, ...
                'class_names_final', {b.classNames});
            save(path, '-struct', 'bundle');
            fprintf('\nSaved model bundle to: %s\n', path);
        end
    end
end
